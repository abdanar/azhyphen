#!/usr/bin/env python3
"""Generate and verify public version metadata from the root VERSION file."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import sys
import tempfile


SEMVER = re.compile(
    r"(?:0|[1-9][0-9]*)\."
    r"(?:0|[1-9][0-9]*)\."
    r"(?:0|[1-9][0-9]*)"
)
VERSION_TOKEN = re.compile(r"(?<![0-9])([0-9]+\.[0-9]+\.[0-9]+)(?![0-9])")
BADGES_START = "<!-- AZHYPHEN-BADGES:START -->"
BADGES_END = "<!-- AZHYPHEN-BADGES:END -->"


class VersionError(ValueError):
    """Raised when canonical or generated version metadata is invalid."""


def read_version(root: Path) -> str:
    path = root / "VERSION"
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise VersionError(f"cannot read VERSION: {exc}") from exc
    if not raw.endswith("\n") or raw.count("\n") != 1:
        raise VersionError("VERSION must contain one version followed by a newline")
    version = raw[:-1]
    if SEMVER.fullmatch(version) is None:
        raise VersionError(f"VERSION is not valid Semantic Versioning: {version!r}")
    return version


def tex_version_bytes(version: str) -> bytes:
    return (
        "% Generated by scripts/update_version.py from VERSION; do not edit.\n"
        f"\\def\\azhyphenversion{{{version}}}\n"
        "\\endinput\n"
    ).encode("utf-8")


def citation_bytes(version: str) -> bytes:
    return (
        "cff-version: 1.2.0\n"
        'message: "If you use this software, please cite it using this metadata."\n'
        "title: azhyphen\n"
        "type: software\n"
        "authors:\n"
        "  - family-names: Abdullayev\n"
        "    given-names: Anar\n"
        f'version: "{version}"\n'
        "license: LPPL-1.3c\n"
    ).encode("utf-8")


def shield_value(value: str) -> str:
    return value.replace("_", "__").replace("-", "--").replace(" ", "%20")


def badges_body(version: str) -> str:
    displayed = shield_value(f"{version}-development")
    return "\n".join(
        (
            f"![Version](https://img.shields.io/badge/version-{displayed}-blue)",
            "![License](https://img.shields.io/badge/license-LPPL%201.3c%2B-blue)",
            "![LuaLaTeX](https://img.shields.io/badge/LuaLaTeX-supported-2ea44f)",
            "![XeLaTeX](https://img.shields.io/badge/XeLaTeX-supported-2ea44f)",
            "![Status](https://img.shields.io/badge/status-active%20development-orange)",
        )
    )


def render_badges(readme: bytes, version: str) -> bytes:
    try:
        readme.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise VersionError(f"README is not valid UTF-8: {exc}") from exc
    start = BADGES_START.encode("utf-8")
    end = BADGES_END.encode("utf-8")
    if readme.count(start) != 1:
        raise VersionError("README must contain exactly one badge start marker")
    if readme.count(end) != 1:
        raise VersionError("README must contain exactly one badge end marker")
    start_at = readme.index(start)
    end_at = readme.index(end)
    if start_at >= end_at:
        raise VersionError("README badge markers are out of order")
    body = badges_body(version).encode("utf-8")
    return readme[: start_at + len(start)] + b"\n" + body + b"\n" + readme[end_at:]


def desired_files(root: Path, version: str) -> dict[Path, bytes]:
    readme_path = root / "README.md"
    try:
        readme = readme_path.read_bytes()
    except OSError as exc:
        raise VersionError(f"cannot read README: {exc}") from exc
    return {
        root / "tex" / "latex" / "azhyphen" / "azhyphen-version.tex": (
            tex_version_bytes(version)
        ),
        root / "CITATION.cff": citation_bytes(version),
        readme_path: render_badges(readme, version),
    }


def runtime_version_errors(root: Path, version: str) -> list[str]:
    package = root / "tex" / "latex" / "azhyphen"
    errors: list[str] = []
    for name in ("azhyphen.sty", "azhyphen.lua", "azhyphen-version.tex"):
        path = package / name
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            errors.append(f"cannot inspect runtime version in {path.name}: {exc}")
            continue
        for found in VERSION_TOKEN.findall(text):
            if found != version:
                errors.append(f"stale runtime version {found} appears in {path.name}")
    return errors


def check_version_state(root: Path) -> list[str]:
    try:
        version = read_version(root)
        desired = desired_files(root, version)
    except VersionError as exc:
        return [str(exc)]
    errors = runtime_version_errors(root, version)
    for path, contents in desired.items():
        if not path.is_file():
            errors.append(f"generated version metadata is missing: {path.name}")
        elif path.read_bytes() != contents:
            errors.append(f"generated version metadata is stale: {path.name}")
    return errors


def atomic_write_if_changed(path: Path, contents: bytes) -> bool:
    if path.is_file() and path.read_bytes() == contents:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
    )
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(contents)
            handle.flush()
            os.fsync(handle.fileno())
        temporary.chmod(0o644)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)
    return True


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--quiet", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    root = args.root.resolve()
    if args.check:
        errors = check_version_state(root)
        if errors:
            for error in errors:
                print(f"error: {error}", file=sys.stderr)
            return 1
        if not args.quiet:
            print(f"version metadata is consistent with {read_version(root)}")
        return 0
    try:
        version = read_version(root)
        desired = desired_files(root, version)
        changed = [
            path.name
            for path, contents in desired.items()
            if atomic_write_if_changed(path, contents)
        ]
    except (OSError, VersionError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if not args.quiet:
        if changed:
            print(f"updated version metadata for {version}: {', '.join(changed)}")
        else:
            print(f"version metadata is already up to date for {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
